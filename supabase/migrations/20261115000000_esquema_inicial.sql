-- VEO Territorios · esquema inicial
-- Deducido de api/main.js. Solo el backend (clave secreta = service_role) accede a estas tablas:
-- RLS activado sin políticas => anon/authenticated no ven nada; service_role omite RLS.

-- ───────────── Usuarios ─────────────
create table if not exists public.veo_users (
  id                    bigint generated by default as identity primary key,
  username              text not null unique check (char_length(username) between 2 and 64),
  display_name          text not null,
  role                  text not null default 'broker'
                        check (role in ('admin','supervisor','broker','legal','tecnico')),
  active                boolean not null default true,
  password_hash         text not null,
  must_change_password  boolean not null default true,
  session_version       integer not null default 1,
  password_changed_at   timestamptz,
  credential_updated_at timestamptz,
  created_at            timestamptz not null default now()
);

-- ───────────── Predios ─────────────
create table if not exists public.veo_predios (
  id                   bigint generated by default as identity primary key,
  code                 text unique,
  corridor_id          integer not null check (corridor_id between 1 and 99),
  alias                text,
  broker_id            bigint references public.veo_users(id) on delete set null,
  created_by           bigint references public.veo_users(id) on delete set null,
  lat                  double precision not null,
  lng                  double precision not null,
  geo_status           text not null default 'pendiente'
                       check (geo_status in ('pendiente','verificado','fuera_corredor')),
  geo_checked_at       timestamptz,
  phase                text not null default 'BUSQUEDA_FACTIBILIDAD'
                       check (phase in ('BUSQUEDA_FACTIBILIDAD','PRIMER_CONTACTO','SEGUIMIENTO','CIERRE')),
  active               boolean not null default true,
  municipio            text,
  direccion            text,
  referencia           text,
  dron_url             text,
  propietario          text,
  telefono             text,
  email                text,
  fecha_contacto       date,
  interes              text default 'sin_contacto'
                       check (interes in ('sin_contacto','evaluando','interesado','rechazado')),
  fecha_carta          date,
  clausula_condicional boolean not null default false,
  permiso_status       text not null default 'no_iniciado'
                       check (permiso_status in ('no_iniciado','en_tramite','autorizado','rechazado')),
  notas                text,
  ratings_json         text,
  score                integer check (score between 0 and 100),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index if not exists veo_predios_broker_idx  on public.veo_predios (broker_id);
create index if not exists veo_predios_updated_idx on public.veo_predios (updated_at desc);

-- ───────────── Documentos (archivos en Storage: bucket veo-documentos) ─────────────
create table if not exists public.veo_documents (
  id                bigint generated by default as identity primary key,
  predio_id         bigint not null references public.veo_predios(id) on delete cascade,
  doc_type          text not null check (doc_type in ('foto','satelital','dron','carta_intencion','contrato',
                      'mecanica_suelos','memoria_calculo','factibilidad_electrica','permiso_municipal','otro')),
  storage_path      text not null unique,
  original_filename text,
  size_bytes        bigint,
  uploaded_by_name  text,
  created_at        timestamptz not null default now()
);
create index if not exists veo_documents_predio_idx on public.veo_documents (predio_id);

-- ───────────── Comentarios ─────────────
create table if not exists public.veo_comments (
  id         bigint generated by default as identity primary key,
  predio_id  bigint not null references public.veo_predios(id) on delete cascade,
  user_id    bigint references public.veo_users(id) on delete set null,
  author     text,
  body       text not null,
  created_at timestamptz not null default now()
);
create index if not exists veo_comments_predio_idx on public.veo_comments (predio_id);

-- ───────────── Solicitudes de cambio de fase ─────────────
create table if not exists public.veo_requests (
  id             bigint generated by default as identity primary key,
  predio_id      bigint not null references public.veo_predios(id) on delete cascade,
  from_phase     text,
  to_phase       text not null,
  code           text,
  alias          text,
  requester_name text,
  reason         text,
  status         text not null default 'pendiente' check (status in ('pendiente','aprobada','rechazada')),
  review_note    text,
  created_at     timestamptz not null default now()
);
create index if not exists veo_requests_predio_idx on public.veo_requests (predio_id);

-- ───────────── Bitácora / actividad ─────────────
create table if not exists public.veo_activity (
  id         bigint generated by default as identity primary key,
  predio_id  bigint references public.veo_predios(id) on delete cascade,
  user_id    bigint references public.veo_users(id) on delete set null,
  user_name  text,
  kind       text not null,
  detail     text,
  created_at timestamptz not null default now()
);
create index if not exists veo_activity_predio_idx  on public.veo_activity (predio_id);
create index if not exists veo_activity_created_idx on public.veo_activity (created_at desc);

-- ───────────── Seguridad ─────────────
alter table public.veo_users     enable row level security;
alter table public.veo_predios   enable row level security;
alter table public.veo_documents enable row level security;
alter table public.veo_comments  enable row level security;
alter table public.veo_requests  enable row level security;
alter table public.veo_activity  enable row level security;

revoke all on public.veo_users, public.veo_predios, public.veo_documents,
              public.veo_comments, public.veo_requests, public.veo_activity
  from anon, authenticated;
grant all on public.veo_users, public.veo_predios, public.veo_documents,
             public.veo_comments, public.veo_requests, public.veo_activity
  to service_role;
grant usage, select on all sequences in schema public to service_role;

-- ───────────── Storage: bucket privado para expedientes (máx. 45 MB, igual que la API) ─────────────
insert into storage.buckets (id, name, public, file_size_limit)
values ('veo-documentos', 'veo-documentos', false, 47185920)
on conflict (id) do nothing;
